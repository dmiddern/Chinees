import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';
const source=stripTypeScriptTypes(readFileSync(new URL('../src/lib/listCollections.ts',import.meta.url),'utf8'));
const {listCollections}=await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
const words=['words.json','words-hsk4.json','words-hsk5.json','words-hsk6.json','words-hsk7-9-1.json','words-hsk7-9-2.json','words-hsk7-9-3.json','words-hsk7-9-4.json'].flatMap(file=>JSON.parse(readFileSync(new URL(`../src/data/${file}`,import.meta.url),'utf8')));
const own={id:'own-1',name:'Op reis',wordIds:[1,1001],createdAt:1,updatedAt:1};
const mistakes={id:'wrong-1',name:'Nog oefenen',wordIds:[1002],createdAt:2,updatedAt:2,mistakeSessionId:'session-1',direction:'nl-pinyin',mistakes:[{wordId:1002,reason:'wrong'}]};
const legacyMistakes={...mistakes,id:'legacy',mistakeSessionId:undefined};
const lists=[own,mistakes,legacyMistakes];
const snapshot=JSON.stringify(lists);
const collections=listCollections([...words,{id:99999,level:1,custom:true}],lists);
assert.deepEqual(collections.slice(0,7).map(l=>l.name),['HSK 1','HSK 2','HSK 3','HSK 4','HSK 5','HSK 6','HSK 7–9']);
assert.deepEqual(collections.slice(0,7).map(l=>l.wordIds.length),[300,200,500,1000,1600,1800,5605]);
assert.ok(!collections[0].wordIds.includes(99999));
assert.deepEqual(collections.slice(7).map(l=>l.category),['mistakes','mistakes','own']);
assert.equal(collections[7].direction,'nl-pinyin');
assert.deepEqual(collections[7].wordIds,mistakes.wordIds);
assert.deepEqual(collections.at(-1).wordIds,own.wordIds);
assert.equal(JSON.stringify(lists),snapshot,'Bestaande lijsten blijven ongewijzigd');
assert.equal(listCollections(words,[]).length,7);
console.log('Lijsten: alle HSK-niveaus, categorievolgorde, bestaande lijsten, foutgegevens en oefenrichting gecontroleerd.');
